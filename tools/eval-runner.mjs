// ── Slide structure helpers (kept in sync with deck-lint.mjs) ──────────

const FM_KEYS = new Set([
  'layout', 'transition', 'background', 'backgroundSize', 'class', 'clicks',
  'level', 'hide', 'hideInToc', 'title', 'name', 'zoom', 'dragPos',
  'routeAlias', 'disabled', 'preload', 'src', 'image', 'color',
]);

// Count slides, following Slidev `src:` page includes so decks that split
// content across pages/*.md are counted in full. deckDir resolves includes.
function countSlides(md, deckDir, seen = new Set()) {
  const blocks = [[]];
  for (const line of md.split(/\r?\n/)) {
    if (/^---\s*$/.test(line)) blocks.push([]);
    else blocks[blocks.length - 1].push(line);
  }
  const texts = blocks.map(b => b.join('\n'));
  if (texts.length < 3) return texts.some(t => t.trim()) ? 1 : 0;
  const isFrontmatter = (t) => {
    const lines = t.split('\n').map(s => s.trim()).filter(Boolean);
    if (!lines.length) return false;
    return lines.every(l => {
      const m = l.match(/^([A-Za-z_][\w-]*)\s*:/);
      return m && FM_KEYS.has(m[1]);
    });
  };
  const srcOf = (t) => { const m = t.match(/^\s*src:\s*(\S+)/m); return m ? m[1].replace(/['"]/g, '') : null; };

  let count = 0;
  for (let i = 2; i < texts.length; i++) {
    const t = texts[i];
    if (isFrontmatter(t)) {
      const src = srcOf(t);
      const inc = src && deckDir ? join(deckDir, src) : null;
      if (inc && existsSync(inc) && !seen.has(inc)) {
        seen.add(inc);
        count += countSlides(readFileSync(inc, 'utf-8'), dirname(inc), seen);
      } else {
        count += 1;
      }
      i++; // consume the paired body block
    } else if (t.trim()) {
      count += 1; // body-only slide (e.g. the cover)
    }
  }
  return count;
}

function relativeLuminance(hex) {
  let h = hex.replace('#', '');
  if (h.length === 3) h = h.split('').map(c => c + c).join('');
  if (h.length < 6) return 0.5;
  const [r, g, b] = [0, 2, 4].map(i => {
    const s = parseInt(h.slice(i, i + 2), 16) / 255;
    return s <= 0.04045 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

const EMOJI_RE = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2190}-\u{21FF}\u{2B00}-\u{2BFF}\u{FE0F}\u{1F1E6}-\u{1F1FF}]/u;

// ── Deterministic assertion engine ─────────────────────────────────────

function readDeckFile(deckDir, rel) {
  const p = join(deckDir, rel);
  return existsSync(p) ? readFileSync(p, 'utf-8') : null;
}

function tokenValue(deckDir, token) {
  const css = readDeckFile(deckDir, 'styles/tokens.css');
  if (!css) return null;
  const m = css.match(new RegExp(`${token.replace(/[-]/g, '\\$&')}\\s*:\\s*([^;]+);`));
  return m ? m[1].trim() : null;
}

// Returns { status: 'pass'|'fail'|'manual'|'judge', detail }
function runAssert(spec, deckDir) {
  if (!spec) return { status: 'manual', detail: 'no machine assertion' };
  if (spec.judge) return { status: 'judge', detail: 'deferred to LLM judge' };

  const textOf = (file) => readDeckFile(deckDir, file || 'slides.md') || '';
  const norm = (s, ci) => (ci ? s.toLowerCase() : s);

  if ('file_exists' in spec) {
    const ok = existsSync(join(deckDir, spec.file_exists));
    return { status: ok ? 'pass' : 'fail', detail: spec.file_exists };
  }
  if ('slide_count' in spec) {
    const actual = countSlides(textOf('slides.md'), deckDir);
    return { status: actual === spec.slide_count ? 'pass' : 'fail', detail: `expected ${spec.slide_count}, found ${actual}` };
  }
  if ('contains' in spec) {
    const hay = norm(textOf(spec.file), spec.ci);
    const ok = spec.regex ? new RegExp(spec.contains, spec.ci ? 'i' : '').test(textOf(spec.file)) : hay.includes(norm(spec.contains, spec.ci));
    return { status: ok ? 'pass' : 'fail', detail: `"${spec.contains}"` };
  }
  if ('contains_any' in spec) {
    const hay = norm(textOf(spec.file), spec.ci);
    const hit = spec.contains_any.find(s => hay.includes(norm(s, spec.ci)));
    return { status: hit ? 'pass' : 'fail', detail: hit ? `matched "${hit}"` : `none of ${spec.contains_any.length}` };
  }
  if ('contains_all' in spec) {
    const hay = norm(textOf(spec.file), spec.ci);
    const missing = spec.contains_all.filter(s => !hay.includes(norm(s, spec.ci)));
    return { status: missing.length ? 'fail' : 'pass', detail: missing.length ? `missing ${JSON.stringify(missing)}` : 'all present' };
  }
  if ('not_contains_any' in spec) {
    const hay = norm(textOf(spec.file), spec.ci);
    const hit = spec.not_contains_any.find(s => hay.includes(norm(s, spec.ci)));
    return { status: hit ? 'fail' : 'pass', detail: hit ? `found banned "${hit}"` : 'clean' };
  }
  if ('no_emoji' in spec) {
    const ok = !EMOJI_RE.test(textOf(spec.no_emoji));
    return { status: ok ? 'pass' : 'fail', detail: ok ? 'no emoji' : 'emoji present' };
  }
  if ('no_hardcoded_colors_scoped' in spec) {
    const md = textOf('slides.md');
    const styleBlocks = md.match(/<style[^>]*>[\s\S]*?<\/style>/g) || [];
    for (const block of styleBlocks) {
      const m = block.match(/#[0-9a-fA-F]{3,8}\b/);
      if (m) return { status: 'fail', detail: `hardcoded ${m[0]} in scoped style` };
    }
    return { status: 'pass', detail: 'tokens only' };
  }
  if ('token_luma' in spec) {
    const { token, min, max } = spec.token_luma;
    const val = tokenValue(deckDir, token);
    if (!val || !/^#[0-9a-fA-F]{3,8}$/.test(val)) return { status: 'fail', detail: `${token} not a hex color` };
    const l = relativeLuminance(val);
    const ok = (min === undefined || l >= min) && (max === undefined || l <= max);
    return { status: ok ? 'pass' : 'fail', detail: `${token} luma ${l.toFixed(2)}` };
  }
  if ('token_contains' in spec) {
    const { token, value } = spec.token_contains;
    const val = tokenValue(deckDir, token) || '';
    return { status: val.includes(value) ? 'pass' : 'fail', detail: `${token}=${val}` };
  }
  if ('all' in spec) {
    const results = spec.all.map(s => runAssert(s, deckDir));
    const failed = results.find(r => r.status === 'fail');
    if (failed) return { status: 'fail', detail: failed.detail };
    if (results.some(r => r.status === 'judge' || r.status === 'manual')) return { status: 'manual', detail: 'composite needs judge' };
    return { status: 'pass', detail: 'all sub-asserts pass' };
  }
  if ('any' in spec) {
    const results = spec.any.map(s => runAssert(s, deckDir));
    return { status: results.some(r => r.status === 'pass') ? 'pass' : 'fail', detail: 'any-of' };
  }
  return { status: 'manual', detail: 'unknown assert shape' };
}

// ── Output resolution ──────────────────────────────────────────────────

function resolveDeckDir(evalCase, overrides) {
  if (overrides.has(evalCase.id)) return resolve(repoRoot, overrides.get(evalCase.id));
  if (evalCase.files && evalCase.files.length) {
    // update-in-place eval: the deck is where its files live
    const f = evalCase.files.find(p => p.endsWith('slides.md')) || evalCase.files[0];
    return resolve(repoRoot, dirname(f));
  }
  // create eval: prefer a committed fixture, else a freshly generated run dir
  const fixture = resolve(repoRoot, 'evals', 'fixtures', String(evalCase.id));
  if (existsSync(join(fixture, 'slides.md'))) return fixture;
  return resolve(repoRoot, 'evals', 'runs', String(evalCase.id));
}

function maybeGenerate(evalCase, deckDir, genTemplate) {
  if (!genTemplate || existsSync(join(deckDir, 'slides.md'))) return;
  mkdirSync(deckDir, { recursive: true });
  const cmd = genTemplate
    .replaceAll('{prompt}', JSON.stringify(evalCase.prompt))
    .replaceAll('{out}', deckDir)
    .replaceAll('{id}', String(evalCase.id))
    .replaceAll('{files}', (evalCase.files || []).join(' '));
  console.log(`${C.dim}  generating deck for eval ${evalCase.id}: ${cmd}${C.reset}`);
  execSync(cmd, { cwd: repoRoot, stdio: 'inherit' });
}

// ── LLM judge (lazy SDK, prompt-cached rubric, structured JSON) ─────────

const JUDGE_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  properties: {
    assertions: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        properties: {
          name: { type: 'string' },
          pass: { type: 'boolean' },
          reason: { type: 'string' },
        },
        required: ['name', 'pass', 'reason'],
      },
    },
    visual: {
      type: 'object',
      additionalProperties: false,
      properties: {
        transitions: { type: 'integer' },
        reveals: { type: 'integer' },
        annotations: { type: 'integer' },
        motion: { type: 'integer' },
        layout_variety: { type: 'integer' },
        total: { type: 'integer' },
      },
      required: ['transitions', 'reveals', 'annotations', 'motion', 'layout_variety', 'total'],
    },
    slop_tells: { type: 'array', items: { type: 'string' } },
    holdout: {
      type: 'object',
      additionalProperties: false,
      properties: {
        score: { type: 'integer' },
        notes: { type: 'string' },
      },
      required: ['score', 'notes'],
    },
    summary: { type: 'string' },
  },
  required: ['assertions', 'visual', 'slop_tells', 'holdout', 'summary'],
};

const GRADING_INSTRUCTIONS = `You are a strict grader for Slidev presentation decks produced by the slide-maker skill.

You will receive the eval prompt, a list of semantic assertions to judge, and the deck's source files. Do two things:

1. For each listed assertion, decide pass/true or fail/false and give a one-sentence reason grounded in the deck source. Be strict: a vague gesture at the requirement is a fail.

2. Score the deck's VISUAL INTEREST against DECK_RUBRIC.md Part 1: five axes (transitions, reveals, annotations, motion, layout_variety), each 0-4, and their sum as "total" (0-20). Then list any interface-slop tells you find (LLM_TELLS.md "Interface slop"): overused fonts, gradient text, glassmorphism, justified text, pure-black, flat type hierarchy, hero-metric cliche, etc. Empty list means none.

3. Score the deck 0-10 against the HELD-OUT criteria (a separate section below, which the deck's author never saw) and give one or two sentences of notes. Judge these from first principles, NOT from the public rubric. A deck that aces the public rubric but scores low here is the signal to flag — it means the generator satisfied the measured axes without producing something good.

Return ONLY the JSON object matching the provided schema. The rubric definitions follow.`;

// Public rubric files — the same ones the generator compiles against.
const PUBLIC_RUBRIC_FILES = ['docs/DECK_RUBRIC.md', 'docs/LLM_TELLS.md', 'docs/PROJECT_DECK_RUBRIC.md'];
// Held-out file — judge-only, never loaded by the generator (anti-Goodhart).
const HOLDOUT_RUBRIC_FILE = 'evals/holdout-rubric.md';

function readRubricText() {
  const parts = [];
  for (const f of PUBLIC_RUBRIC_FILES) {
    const p = join(repoRoot, f);
    if (existsSync(p)) parts.push(`===== ${f} =====\n${readFileSync(p, 'utf-8')}`);
  }
  const hp = join(repoRoot, HOLDOUT_RUBRIC_FILE);
  if (existsSync(hp)) parts.push(`===== HELD-OUT CRITERIA (author never saw these) =====\n${readFileSync(hp, 'utf-8')}`);
  return parts.join('\n\n');
}

function deckSourceText(deckDir) {
  const parts = [];
  for (const f of ['deck.spec.md', 'slides.md', 'styles/tokens.css', 'styles/theme.css']) {
    const c = readDeckFile(deckDir, f);
    if (c) parts.push(`----- ${f} -----\n${c.slice(0, 24000)}`);
  }
  return parts.join('\n\n');
}

function extractText(message) {
  return (message.content || []).filter(b => b.type === 'text').map(b => b.text).join('');
}

async function judgeDeck(evalCase, deckDir, judgeAssertions, rubricText) {
  let Anthropic;
  try {
    ({ default: Anthropic } = await import('@anthropic-ai/sdk'));
  } catch {
    throw new Error('@anthropic-ai/sdk not installed — run `npm i @anthropic-ai/sdk` to use --judge');
  }
  if (!process.env.ANTHROPIC_API_KEY) throw new Error('ANTHROPIC_API_KEY not set — required for --judge');

  const client = new Anthropic();
  const assertionList = judgeAssertions.map(a => `- ${a.name}: ${a.check}`).join('\n') || '(none)';
  const user =
    `EVAL PROMPT:\n${evalCase.prompt}\n\n` +
    `EXPECTED OUTPUT:\n${evalCase.expected_output}\n\n` +
    `ASSERTIONS TO JUDGE:\n${assertionList}\n\n` +
    `DECK SOURCE:\n${deckSourceText(deckDir)}`;

  const resp = await client.messages.create({
    model: 'claude-opus-4-7',
    max_tokens: 8000,
    thinking: { type: 'adaptive' },
    output_config: {
      effort: process.env.EVAL_JUDGE_EFFORT || 'high',
      format: { type: 'json_schema', schema: JUDGE_SCHEMA },
    },
    // Stable rubric/instructions first (prompt-cached); volatile deck content in messages.
    system: [
      { type: 'text', text: GRADING_INSTRUCTIONS },
      { type: 'text', text: rubricText, cache_control: { type: 'ephemeral' } },
    ],
    messages: [{ role: 'user', content: user }],
  });
  return JSON.parse(extractText(resp));
}

// ── Verdict merge (shared by SDK judge, sub-agent handoff) ─────────────

// Folds a judge verdict ({assertions, visual, slop_tells, summary}) into the
// deterministic results, resolving every assertion still in 'judge' status.
function applyVerdict(results, verdict) {
  const byName = new Map((verdict.assertions || []).map(j => [j.name, j]));
  for (const r of results) {
    if (r.status !== 'judge') continue;
    const j = byName.get(r.name);
    if (j) { r.status = j.pass ? 'pass' : 'fail'; r.detail = j.reason; }
    else { r.status = 'manual'; r.detail = 'judge returned no verdict'; }
  }
  return { visual: verdict.visual ?? null, slopTells: verdict.slop_tells ?? null, holdout: verdict.holdout ?? null, summary: verdict.summary ?? null };
}

// ── Sub-agent handoff (request → results) ──────────────────────────────

const DECK_FILES = ['deck.spec.md', 'slides.md', 'styles/tokens.css', 'styles/theme.css', 'styles/index.css'];

// Build a tasks document for the orchestrating agent to dispatch one grading
// sub-agent per deck. References files by path (the sub-agent has read tools)
// rather than embedding rubric/deck text.
function buildJudgeTasks(cases, reports) {
  const byId = new Map(cases.map(c => [c.id, c]));
  const tasks = [];
  for (const rep of reports) {
    if (rep.skipped) continue;
    const c = byId.get(rep.id);
    const deferred = rep.results
      .filter(r => r.status === 'judge')
      .map(r => ({ name: r.name, check: (c.assertions.find(x => x.name === r.name) || {}).check || '' }));
    tasks.push({
      id: rep.id,
      deckDir: rep.deckDir,
      prompt: c.prompt,
      expected_output: c.expected_output,
      assertions_to_judge: deferred,
      deck_files: DECK_FILES.filter(f => existsSync(join(rep.deckDir, f))),
    });
  }
  return {
    skill: 'slide-maker',
    when: new Date().toISOString(),
    instructions: GRADING_INSTRUCTIONS,
    rubric_files: PUBLIC_RUBRIC_FILES.filter(f => existsSync(join(repoRoot, f))),
    holdout_rubric_file: existsSync(join(repoRoot, HOLDOUT_RUBRIC_FILE)) ? HOLDOUT_RUBRIC_FILE : null,
    result_schema: JUDGE_SCHEMA,
    how_to_respond: 'Dispatch one sub-agent per task. Each reads rubric_files + holdout_rubric_file + the task deck_files (under deckDir), grades assertions_to_judge, scores DECK_RUBRIC visual axes, lists slop tells, scores the held-out criteria 0-10, and appends an object {id, assertions:[{name,pass,reason}], visual:{...,total}, slop_tells:[], holdout:{score,notes}, summary} to results[]. Write to a JSON file (or one file per deck in a dir), then run: node tools/eval-runner.mjs --judge-results <path>',
    results: [],
    tasks,
  };
}

// Load sub-agent verdicts. Accepts a single JSON file or a directory of them.
// Each file is either {results:[...]} or a bare array of verdicts.
function loadJudgeResults(p) {
  const abs = resolve(repoRoot, p);
  const files = [];
  if (statSync(abs).isDirectory()) {
    for (const f of readdirSync(abs)) if (f.endsWith('.json')) files.push(join(abs, f));
  } else {
    files.push(abs);
  }
  const map = new Map();
  for (const f of files) {
    const data = JSON.parse(readFileSync(f, 'utf-8'));
    const arr = Array.isArray(data) ? data : (data.results || []);
    for (const v of arr) if (v && v.id !== undefined) map.set(v.id, v);
  }
  return map;
}

// ── Grade one eval ─────────────────────────────────────────────────────

async function gradeEval(evalCase, opts, rubricText) {
  const deckDir = resolveDeckDir(evalCase, opts.overrides);
  maybeGenerate(evalCase, deckDir, opts.generate);

  if (!existsSync(join(deckDir, 'slides.md'))) {
    return { id: evalCase.id, deckDir, skipped: true, reason: `no deck at ${deckDir} (run the skill on the prompt, or pass --deck ${evalCase.id}=<path>)`, results: [] };
  }

  const results = [];
  const judgeQueue = [];
  for (const a of evalCase.assertions) {
    const r = runAssert(a.assert, deckDir);
    if (r.status === 'judge') judgeQueue.push(a);
    results.push({ name: a.name, status: r.status, detail: r.detail });
  }

  let judgeError = null;
  let visual = null;
  let slopTells = null;
  let holdout = null;
  let summary = null;
  const preset = opts.judgeResults && opts.judgeResults.get(evalCase.id);
  if (preset) {
    // Sub-agent handoff: verdict already produced by a dispatched grading agent.
    ({ visual, slopTells, holdout, summary } = applyVerdict(results, preset));
  } else if (opts.judge) {
    // SDK judge: call Claude directly.
    try {
      ({ visual, slopTells, holdout, summary } = applyVerdict(results, await judgeDeck(evalCase, deckDir, judgeQueue, rubricText)));
    } catch (e) {
      judgeError = e.message;
    }
  }

  const counted = results.filter(r => r.status === 'pass' || r.status === 'fail');
  const passed = counted.filter(r => r.status === 'pass').length;
  return {
    id: evalCase.id, deckDir, skipped: false, results,
    passed, counted: counted.length,
    deferred: results.filter(r => r.status === 'judge' || r.status === 'manual').length,
    visual, slopTells, holdout, summary, judgeError,
  };
}

// ── Trend tracking (#1 meta-signals over time) ─────────────────────────

const HISTORY_FILE = 'evals/history.jsonl';

// Append a compact record of this run so drift can be tracked across runs.
function recordRun(suiteName, reports) {
  const graded = reports.filter(r => !r.skipped);
  const rec = {
    when: new Date().toISOString(),
    skill: suiteName,
    totals: { pass: graded.reduce((s, r) => s + r.passed, 0), count: graded.reduce((s, r) => s + r.counted, 0) },
    evals: graded.map(r => ({
      id: r.id,
      passed: r.passed,
      counted: r.counted,
      visual: r.visual ? r.visual.total : null,
      holdout: r.holdout ? r.holdout.score : null,
      slop: r.slopTells ? r.slopTells.length : null,
    })),
  };
  const out = join(repoRoot, HISTORY_FILE);
  mkdirSync(dirname(out), { recursive: true });
  appendFileSync(out, JSON.stringify(rec) + '\n');
  return rec;
}

const mean = (xs) => { const v = xs.filter(x => x != null); return v.length ? v.reduce((a, b) => a + b, 0) / v.length : null; };
const stdev = (xs) => { const v = xs.filter(x => x != null); if (v.length < 2) return null; const m = mean(v); return Math.sqrt(v.reduce((a, b) => a + (b - m) ** 2, 0) / v.length); };
const fmt = (x, d = 1) => (x == null ? '—' : x.toFixed(d));

// Read history.jsonl and report drift — not just the latest number, but how the
// distribution of scores is shifting (the blog's meta-signal idea).
function showTrend(limit = 8) {
  const p = join(repoRoot, HISTORY_FILE);
  if (!existsSync(p)) { console.log(`${C.dim}no history yet — run with --record first${C.reset}`); return; }
  const recs = readFileSync(p, 'utf-8').split('\n').filter(Boolean).map(l => JSON.parse(l));
  const recent = recs.slice(-limit);

  console.log(`${C.bold}${C.magenta}eval-trend${C.reset}  ${C.dim}last ${recent.length} of ${recs.length} run(s)${C.reset}\n`);
  console.log(`  ${C.dim}${'when'.padEnd(20)} ${'pass%'.padStart(6)} ${'visual̄'.padStart(7)} ${'hold̄'.padStart(6)} ${'slopΣ'.padStart(6)}${C.reset}`);
  const row = (r) => {
    const pct = r.totals.count ? Math.round((r.totals.pass / r.totals.count) * 100) : 0;
    const v = mean(r.evals.map(e => e.visual));
    const h = mean(r.evals.map(e => e.holdout));
    const slop = r.evals.reduce((s, e) => s + (e.slop || 0), 0);
    return { pct, v, h, slop, when: r.when.slice(0, 19).replace('T', ' ') };
  };
  for (const r of recent) {
    const m = row(r);
    console.log(`  ${m.when.padEnd(20)} ${String(m.pct).padStart(5)}% ${fmt(m.v).padStart(7)} ${fmt(m.h).padStart(6)} ${String(m.slop).padStart(6)}`);
  }

  console.log('');
  if (recent.length < 2) { console.log(`  ${C.dim}need 2+ runs to show drift${C.reset}`); return; }
  const a = row(recent[recent.length - 2]);
  const b = row(recent[recent.length - 1]);
  const flags = [];
  const dPct = b.pct - a.pct;
  if (Math.abs(dPct) >= 10) flags.push(`assertion pass-rate moved ${dPct > 0 ? '+' : ''}${dPct} points`);
  if (a.v != null && b.v != null && Math.abs(b.v - a.v) >= 2) flags.push(`mean visual moved ${(b.v - a.v > 0 ? '+' : '')}${(b.v - a.v).toFixed(1)}`);
  if (a.h != null && b.h != null && Math.abs(b.h - a.h) >= 2) flags.push(`mean holdout moved ${(b.h - a.h > 0 ? '+' : '')}${(b.h - a.h).toFixed(1)}`);

  // Goodhart: public visual high but held-out low on the latest run.
  const latest = recent[recent.length - 1];
  if (b.v != null && b.h != null && (b.v / 2 - b.h) >= 3) flags.push(`Goodhart gap: mean visual ${(b.v / 2).toFixed(1)}/10 vs holdout ${b.h.toFixed(1)}/10`);

  // Character shift: visual scores collapsing to uniform across decks can mean gaming.
  const sdA = stdev(recent[recent.length - 2].evals.map(e => e.visual));
  const sdB = stdev(latest.evals.map(e => e.visual));
  if (sdA != null && sdB != null && sdA - sdB >= 2) flags.push(`visual spread collapsed (σ ${sdA.toFixed(1)} → ${sdB.toFixed(1)}) — scores converging, check for gaming`);

  if (flags.length) {
    console.log(`  ${C.yellow}${C.bold}meta-signals (latest vs previous):${C.reset}`);
    for (const f of flags) console.log(`  ${DOT} ${C.yellow}${f}${C.reset}`);
  } else {
    console.log(`  ${CHECK} no significant drift between the last two runs`);
  }
}

// ── CLI ────────────────────────────────────────────────────────────────

function parseArgs(argv) {
  const opts = { judge: false, only: new Set(), overrides: new Map(), generate: null, json: null, emitJudgeTasks: null, judgeResultsPath: null, record: false, trend: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--judge') opts.judge = true;
    else if (a === '--record') opts.record = true;
    else if (a === '--trend') opts.trend = true;
    else if (a === '--eval') opts.only.add(Number(argv[++i]));
    else if (a === '--generate') opts.generate = argv[++i];
    else if (a === '--json') opts.json = argv[++i];
    else if (a === '--emit-judge-tasks') opts.emitJudgeTasks = argv[++i];
    else if (a === '--judge-results') opts.judgeResultsPath = argv[++i];
    else if (a === '--deck') {
      const [id, ...rest] = argv[++i].split('=');
      opts.overrides.set(Number(id), rest.join('='));
    } else if (a === '-h' || a === '--help') opts.help = true;
    else { console.error(`Unknown argument: ${a}`); process.exit(2); }
  }
  return opts;
}

function symbol(status) {
  return status === 'pass' ? CHECK : status === 'fail' ? CROSS : status === 'judge' ? DOT : SKIP;
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) {
    console.log(readFileSync(new URL(import.meta.url)).toString().split('\n').filter(l => l.startsWith('//')).map(l => l.slice(3)).join('\n'));
    return;
  }
  if (opts.trend) { showTrend(); return; } // read-only: analyse history, don't grade

  const evalsPath = join(repoRoot, 'evals', 'evals.json');
  const suite = JSON.parse(readFileSync(evalsPath, 'utf-8'));
  let cases = suite.evals;
  if (opts.only.size) cases = cases.filter(c => opts.only.has(c.id));

  if (opts.judgeResultsPath) opts.judgeResults = loadJudgeResults(opts.judgeResultsPath);
  const rubricText = opts.judge ? readRubricText() : '';

  const mode = opts.judgeResults ? ', sub-agent verdicts loaded' : opts.judge ? ', SDK judge ON' : opts.emitJudgeTasks ? ', emitting judge tasks' : '';
  console.log(`${C.bold}${C.magenta}eval-runner${C.reset}  ${C.dim}${suite.skill_name} — ${cases.length} eval(s)${mode}${C.reset}`);

  const reports = [];
  for (const evalCase of cases) {
    reports.push(await gradeEval(evalCase, opts, rubricText));
  }

  // Console report
  for (const rep of reports) {
    console.log('');
    if (rep.skipped) {
      console.log(`${SKIP} ${C.bold}eval ${rep.id}${C.reset} ${C.dim}SKIPPED — ${rep.reason}${C.reset}`);
      continue;
    }
    const pct = rep.counted ? Math.round((rep.passed / rep.counted) * 100) : 0;
    const head = rep.passed === rep.counted ? C.green : C.yellow;
    console.log(`${head}${C.bold}eval ${rep.id}${C.reset}  ${head}${rep.passed}/${rep.counted} assertions${C.reset} ${C.dim}(${pct}%)${rep.deferred ? `, ${rep.deferred} deferred` : ''}${C.reset}  ${C.dim}${basename(rep.deckDir)}${C.reset}`);
    for (const r of rep.results) {
      console.log(`  ${symbol(r.status)} ${r.name} ${C.dim}— ${r.detail}${C.reset}`);
    }
    if (rep.judgeError) console.log(`  ${CROSS} ${C.red}judge error: ${rep.judgeError}${C.reset}`);
    if (rep.visual) console.log(`  ${C.cyan}visual ${rep.visual.total}/20${C.reset} ${C.dim}(transitions ${rep.visual.transitions}, reveals ${rep.visual.reveals}, annotations ${rep.visual.annotations}, motion ${rep.visual.motion}, layout ${rep.visual.layout_variety})${C.reset}`);
    if (rep.slopTells && rep.slopTells.length) console.log(`  ${DOT} ${C.yellow}slop: ${rep.slopTells.join('; ')}${C.reset}`);
    if (rep.holdout) {
      console.log(`  ${C.cyan}holdout ${rep.holdout.score}/10${C.reset} ${C.dim}— ${rep.holdout.notes}${C.reset}`);
      if (rep.visual) {
        const gap = rep.visual.total / 2 - rep.holdout.score; // both on a /10 scale
        if (gap >= 3) console.log(`  ${DOT} ${C.yellow}Goodhart signal: public visual ${(rep.visual.total / 2).toFixed(1)}/10 vs holdout ${rep.holdout.score}/10 (gap ${gap.toFixed(1)}) — aces the measured rubric, weak on held-out quality${C.reset}`);
      }
    }
  }

  // Summary
  const graded = reports.filter(r => !r.skipped);
  const totalPass = graded.reduce((s, r) => s + r.passed, 0);
  const totalCount = graded.reduce((s, r) => s + r.counted, 0);
  console.log('');
  console.log(`${C.bold}${'═'.repeat(50)}${C.reset}`);
  console.log(`${C.bold}Summary${C.reset}  ${graded.length} graded, ${reports.length - graded.length} skipped`);
  if (totalCount) console.log(`  ${totalPass}/${totalCount} assertions passed ${C.dim}(${Math.round((totalPass / totalCount) * 100)}%)${C.reset}`);

  if (opts.emitJudgeTasks) {
    const tasksDoc = buildJudgeTasks(cases, reports);
    const out = resolve(repoRoot, opts.emitJudgeTasks);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, JSON.stringify(tasksDoc, null, 2));
    console.log(`\n${C.cyan}judge tasks written to ${opts.emitJudgeTasks}${C.reset} ${C.dim}(${tasksDoc.tasks.length} deck(s))${C.reset}`);
    console.log(`${C.dim}dispatch one grading sub-agent per task (rubric_files + deck_files), collect results, then: node tools/eval-runner.mjs --judge-results <path>${C.reset}`);
    process.exit(0);
  }

  if (opts.json) {
    const out = resolve(repoRoot, opts.json);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, JSON.stringify({ skill: suite.skill_name, when: new Date().toISOString(), judge: opts.judge || !!opts.judgeResults, reports }, null, 2));
    console.log(`\n${C.dim}report written to ${opts.json}${C.reset}`);
  }

  if (opts.record) {
    recordRun(suite.skill_name, reports);
    console.log(`\n${C.dim}run appended to ${HISTORY_FILE} — see drift with: node tools/eval-runner.mjs --trend${C.reset}`);
  }

  const anyFail = graded.some(r => r.results.some(x => x.status === 'fail'));
  process.exit(anyFail ? 1 : 0);
}

main().catch(e => { console.error(`${C.red}${e.stack || e.message}${C.reset}`); process.exit(2); });
