#!/usr/bin/env node
// eval-runner.mjs — run the slide-maker eval suite (evals/evals.json).
//
// Pipeline per eval:  resolve output deck  →  grade  →  score  →  report.
//
//   • Deterministic grading runs anywhere with zero dependencies. Each
//     assertion in evals.json carries a machine-runnable `assert` spec
//     alongside its prose `check`.
//   • Semantic assertions (`assert: {judge:true}`) and a rubric score are
//     graded by a judge. Two judge backends:
//       --judge          call Claude directly (needs ANTHROPIC_API_KEY +
//                        `npm i @anthropic-ai/sdk`). Good for unattended CI.
//       sub-agent handoff  --emit-judge-tasks <path> writes per-deck grading
//                        tasks (rubric + deck file paths); the orchestrating
//                        agent dispatches one grading sub-agent per task, then
//                        --judge-results <path> folds the verdicts into scores.
//                        No API key needed — reuses the agent's model access.
//
// Output decks are NOT generated by this runner by default — generation is the
// skill's job. Point the runner at outputs via convention or flags:
//   • update evals (those with a `files` list) grade the deck those files live in
//   • create evals grade  evals/runs/<id>/  (or use --deck <id>=<path>)
//   • --generate "<cmd>"  runs a command to produce a missing deck first
//
// Usage:
//   node tools/eval-runner.mjs [options]
//     --judge                 run the SDK judge (rubric + semantic asserts)
//     --emit-judge-tasks <p>  write grading tasks for sub-agent dispatch
//     --judge-results <p>     fold sub-agent verdicts (file or dir) into scores
//     --eval <id>             run only one eval by id (repeatable)
//     --deck <id>=<path>      override the output deck dir for an eval
//     --generate "<cmd>"      run <cmd> to produce a missing deck. Tokens:
//                             {prompt} {out} {id} are substituted.
//     --json <path>           also write the report JSON here
//     --record                append this run to evals/history.jsonl
//     --trend                 analyse history.jsonl for score drift, then exit
//     -h, --help              show this help
//
// The judge also scores a HELD-OUT rubric (evals/holdout-rubric.md) the deck
// generator never sees — a deck that aces the public rubric but scores low on
// holdout is flagged as a Goodhart signal.

